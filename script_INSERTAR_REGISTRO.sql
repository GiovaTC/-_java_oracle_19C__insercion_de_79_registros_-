CREATE TABLE REGISTROS_79 (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100),
    EDAD NUMBER,
    FECHA_REGISTRO DATE,

    CONSTRAINT PK_REGISTROS_79
        PRIMARY KEY (ID)
);

COMMIT;

-- verificar tabla .
SELECT TABLE_NAME 
FROM USER_TABLES WHERE TABLE_NAME = 'REGISTROS_79';

-- PROCEDIMIENTO ALMACENADO PARA INSERTAR .
CREATE OR REPLACE PROCEDURE INSERTAR_REGISTRO (
    P_NOMBRE IN VARCHAR2,
    P_EDAD IN NUMBER
)
AS
BEGIN

    INSERT INTO REGISTROS_79 (
        NOMBRE,
        EDAD,
        FECHA_REGISTRO
    )
    VALUES (
        P_NOMBRE,
        P_EDAD,
        SYSDATE
    );

    COMMIT;

END;
/

COMMIT;

-- verificar el procedimiento SP.
SELECT OBJECT_NAME,
       OBJECT_TYPE,
       STATUS
FROM USER_OBJECTS WHERE OBJECT_NAME = 'INSERTAR_REGISTRO';